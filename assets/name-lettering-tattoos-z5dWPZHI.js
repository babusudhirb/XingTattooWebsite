<ul>
<li><strong>Letter spacing</strong> keeps words readable.</li>
<li><strong>Line spacing</strong> stops stacked lines from merging.</li>
<li><strong>Stroke thickness</strong> that's consistent ages more evenly.</li>
<li><strong>Bold strokes</strong> usually last longer than very thin ones.</li>
</ul>
